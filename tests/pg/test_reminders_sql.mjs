// 15th update (11.16): call reminders. Real migrations on a real Postgres.
// Run:  cd tests/pg && node test_reminders_sql.mjs
import { freshDb, addUser, as } from "./db.mjs";
import { randomUUID as uuid } from "crypto";

let ok = 0, fail = 0;
const check = (label, cond, extra) => { if (cond) { ok++; console.log("  PASS", label); } else { fail++; console.log("  FAIL", label, extra !== undefined ? JSON.stringify(extra).slice(0, 300) : ""); } };
const U = { gio: uuid(), tim: uuid(), james: uuid(), gone: uuid() };
const db = await freshDb({ twice: true });
check("all migrations (1 to 15) run, and run again safely", true);
await addUser(db, U.gio, "gio"); await addUser(db, U.tim, "tim"); await addUser(db, U.james, "james", { role: "admin" }); await addUser(db, U.gone, "gone", { active: false });
await db.query("insert into public.leads (id, name, phone) values ('L1', 'Maple Roofing', '519-555-0101')");
const v = async (who, sql, p = []) => { const r = await as(db, who && U[who], sql, p); return r.ok ? r.rows[0].v : r; };
const save = (who, o) => v(who, "select public.rem_save($1::jsonb) as v", [JSON.stringify(o)]);
const AT = "2026-11-20T14:30:00-05:00";

let r = await save("gio", { lead_id: "L1", remind_at: AT, company: "Maple Roofing", owner_name: "Sam Lee", phone: "519-555-0101", address: "1 King St", website: "maple.ca", btype: "Roofing", notes: "Call back about the website quote" });
check("Gio sets a reminder with the business details, owner and notes", r.id && r.company === "Maple Roofing" && r.owner_name === "Sam Lee" && r.notes.startsWith("Call back") && r.lead_id === "L1" && !("owner_id" in r), r);
const id = r.id;
r = await v("gio", "select public.rem_list() as v");
check("Gio sees it", r.length === 1 && r[0].id === id && new Date(r[0].remind_at).toISOString() === new Date(AT).toISOString(), r);
r = await v("tim", "select public.rem_list() as v");
check("Tim doesn't see Gio's reminders", r.length === 0, r);
r = await v("james", "select public.rem_list() as v");
check("an admin doesn't see them either (they're private)", r.length === 0, r);
r = await as(db, U.james, "select count(*)::int as n from public.reminders");
check("...not even reading the table directly", r.ok && r.rows[0].n === 0, r);
r = await v("tim", "select public.rem_done($1, true) as v", [id]);
check("Tim can't tick off Gio's reminder", r.ok === false && /not found/.test(r.error), r);
r = await v("tim", "select public.rem_delete($1) as v", [id]);
check("...or delete it", r.ok === false, r);
r = await as(db, U.tim, "update public.reminders set notes = 'x' where id = $1", [id]);
check("...or change it directly", r.ok && r.affected === 0, r);
r = await save("gio", { remind_at: "tomorrow", company: "X" });
check("a made-up time is refused", r.ok === false && /date and time/.test(r.error), r);
r = await save("gio", { remind_at: AT, company: "" });
check("a business name is required", r.ok === false, r);
r = await save("gio", { remind_at: AT, company: "Ghost Co", lead_id: "NOPE" });
check("an unknown lead is simply not linked", r.lead_id === null, r);
await v("gio", "select public.rem_delete($1) as v", [r.id]);
r = await save("gone", { remind_at: AT, company: "X" });
check("a deactivated person can't set reminders", r.ok === false, r);
r = await v(null, "select public.rem_list() as v");
check("signed-out visitors get nothing", r.ok === false || (Array.isArray(r) && r.length === 0), r);
r = await v("gio", "select public.rem_snooze($1, $2) as v", [id, "2026-11-21T09:00:00-05:00"]);
check("snoozing moves it", new Date(r.remind_at).toISOString() === new Date("2026-11-21T09:00:00-05:00").toISOString(), r);
r = await v("gio", "select public.rem_done($1, true) as v", [id]);
check("Gio ticks it off", r.done_at !== null, r);
r = await v("gio", "select public.rem_list() as v");
check("done reminders stay in the list for 30 days", r.length === 1 && r[0].done_at, r);
r = await save("gio", { id, remind_at: AT, company: "Maple Roofing", notes: "Updated" });
check("editing it brings it back", r.done_at === null && r.notes === "Updated", r);
await db.query("delete from public.leads where id = 'L1'");
r = await v("gio", "select public.rem_list() as v");
check("if the business is removed, the reminder keeps its copy of the details", r.length === 1 && r[0].lead_id === null && r[0].company === "Maple Roofing", r);
r = await v("gio", "select public.rem_delete($1) as v", [id]);
check("Gio deletes it", r.ok === true && (await v("gio", "select public.rem_list() as v")).length === 0, r);
console.log(`\n${ok} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
